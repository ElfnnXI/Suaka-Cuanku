'use client';

import { useState } from 'react';
import DashboardLayout from '@/components/dashboard/DashboardLayout';
import { FileText, Download, RefreshCw, Calendar, Users, DollarSign, TrendingUp, Shield } from 'lucide-react';
import { apiFetch } from '@/lib/client-api';

interface AuditReport {
  generatedAt: string;
  generatedBy: {
    id: string;
    name: string;
    email: string;
  };
  userStats: {
    totalUsers: number;
    totalAdmins: number;
    totalAuditors: number;
    riskDistribution: {
      LOW: number;
      MEDIUM: number;
      HIGH: number;
    };
  };
  loanStats: {
    totalLoans: number;
    totalLoanAmount: number;
    statusDistribution: {
      PENDING: number;
      APPROVED: number;
      REJECTED: number;
      PAID: number;
    };
  };
  paymentStats: {
    totalPayments: number;
    totalDebt: number;
    totalPaid: number;
    remainingDebt: number;
    statusDistribution: {
      PENDING: number;
      PAID: number;
      REJECTED: number;
    };
  };
  auditTrail: {
    totalAuditLogs: number;
    recentActivity: Array<{
      id: string;
      action: string;
      description: string;
      createdAt: string;
    }>;
  };
}

export default function AuditorReportsPage() {
  const [report, setReport] = useState<AuditReport | null>(null);
  const [loading, setLoading] = useState(false);

  const generateReport = async () => {
    setLoading(true);
    try {
      const res = await apiFetch('/api/auditor/audit-report');
      const data = await res.json();
      if (data.report) {
        setReport(data.report);
      }
    } catch (error) {
      console.error('Failed to generate report:', error);
    } finally {
      setLoading(false);
    }
  };

  const exportReport = () => {
    if (!report) return;

    const reportText = `
LAPORAN AUDIT - SUAKA CUANKU
Generated: ${new Date(report.generatedAt).toLocaleString('id-ID')}
Generated By: ${report.generatedBy.name} (${report.generatedBy.email})

=== STATISTIK USER ===
Total User: ${report.userStats.totalUsers}
Total Admin: ${report.userStats.totalAdmins}
Total Auditor: ${report.userStats.totalAuditors}

Distribusi Risiko:
- Low: ${report.userStats.riskDistribution.LOW}
- Medium: ${report.userStats.riskDistribution.MEDIUM}
- High: ${report.userStats.riskDistribution.HIGH}

=== STATISTIK PINJAMAN ===
Total Pinjaman: ${report.loanStats.totalLoans}
Total Nominal: Rp ${report.loanStats.totalLoanAmount.toLocaleString('id-ID')}

Status Pinjaman:
- Pending: ${report.loanStats.statusDistribution.PENDING}
- Approved: ${report.loanStats.statusDistribution.APPROVED}
- Rejected: ${report.loanStats.statusDistribution.REJECTED}
- Paid: ${report.loanStats.statusDistribution.PAID}

=== STATISTIK PEMBAYARAN ===
Total Pembayaran: ${report.paymentStats.totalPayments}
Total Hutang: Rp ${report.paymentStats.totalDebt.toLocaleString('id-ID')}
Sudah Terbayar: Rp ${report.paymentStats.totalPaid.toLocaleString('id-ID')}
Sisa Hutang: Rp ${report.paymentStats.remainingDebt.toLocaleString('id-ID')}

Status Pembayaran:
- Pending: ${report.paymentStats.statusDistribution.PENDING}
- Paid: ${report.paymentStats.statusDistribution.PAID}
- Rejected: ${report.paymentStats.statusDistribution.REJECTED}

=== AUDIT TRAIL ===
Total Log Audit: ${report.auditTrail.totalAuditLogs}

Aktivitas Terbaru:
${report.auditTrail.recentActivity.map(activity => 
  `- ${new Date(activity.createdAt).toLocaleString('id-ID')}: ${activity.description}`
).join('\n')}
    `.trim();

    const blob = new Blob([reportText], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `audit-report-${new Date().toISOString().split('T')[0]}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const formatRupiah = (amount: number) => {
    return `Rp ${amount.toLocaleString('id-ID')}`;
  };

  return (
    <DashboardLayout role="AUDITOR">
      <div className="space-y-8">
        {/* Header */}
        <div className="flex items-center justify-between">
          <div>
            <h1 className="text-3xl font-bold text-white mb-2" style={{ fontFamily: 'Poppins, sans-serif' }}>
              Laporan Audit
            </h1>
            <p className="text-gray-400">Generate dan export laporan audit komprehensif</p>
          </div>
          <div className="flex gap-3">
            <button
              onClick={generateReport}
              disabled={loading}
              className="flex items-center gap-2 px-4 py-2 bg-cyan-600 hover:bg-cyan-700 rounded-xl transition-colors text-white disabled:opacity-50"
            >
              <RefreshCw className={`w-4 h-4 ${loading ? 'animate-spin' : ''}`} />
              <span>{loading ? 'Generating...' : 'Generate Laporan'}</span>
            </button>
            {report && (
              <button
                onClick={exportReport}
                className="flex items-center gap-2 px-4 py-2 bg-green-600 hover:bg-green-700 rounded-xl transition-colors text-white"
              >
                <Download className="w-4 h-4" />
                <span>Export</span>
              </button>
            )}
          </div>
        </div>

        {!report ? (
          <div className="bg-white/10 backdrop-blur-sm border border-white/20 rounded-2xl p-12 text-center">
            <FileText className="w-16 h-16 text-cyan-400 mx-auto mb-4" />
            <h3 className="text-xl font-semibold text-white mb-2">Belum Ada Laporan</h3>
            <p className="text-gray-400 mb-6">Klik tombol "Generate Laporan" untuk membuat laporan audit komprehensif</p>
          </div>
        ) : (
          <div className="space-y-6">
            {/* Report Header */}
            <div className="bg-white/10 backdrop-blur-sm border border-white/20 rounded-2xl p-6 shadow-xl">
              <div className="flex items-center gap-3 mb-4">
                <FileText className="w-6 h-6 text-cyan-400" />
                <h2 className="text-xl font-bold text-white">Laporan Audit Komprehensif</h2>
              </div>
              <div className="grid grid-cols-2 gap-4 text-sm text-gray-400">
                <div>
                  <span className="font-medium">Dibuat:</span> {new Date(report.generatedAt).toLocaleString('id-ID')}
                </div>
                <div>
                  <span className="font-medium">Oleh:</span> {report.generatedBy.name} ({report.generatedBy.email})
                </div>
              </div>
            </div>

            {/* User Stats */}
            <div className="bg-white/10 backdrop-blur-sm border border-white/20 rounded-2xl p-6 shadow-xl">
              <h3 className="text-xl font-bold text-white mb-6 flex items-center gap-2">
                <Users className="w-5 h-5 text-blue-400" />
                Statistik User
              </h3>
              <div className="grid grid-cols-3 gap-4 mb-6">
                <div className="text-center">
                  <div className="text-3xl font-bold text-blue-400">{report.userStats.totalUsers}</div>
                  <div className="text-sm text-gray-400">User</div>
                </div>
                <div className="text-center">
                  <div className="text-3xl font-bold text-purple-400">{report.userStats.totalAdmins}</div>
                  <div className="text-sm text-gray-400">Admin</div>
                </div>
                <div className="text-center">
                  <div className="text-3xl font-bold text-cyan-400">{report.userStats.totalAuditors}</div>
                  <div className="text-sm text-gray-400">Auditor</div>
                </div>
              </div>
              <div className="space-y-3">
                <div className="flex justify-between items-center p-3 bg-gray-700/40 rounded-xl">
                  <span className="text-gray-400">Risiko Low</span>
                  <span className="text-lg font-bold text-green-400">{report.userStats.riskDistribution.LOW}</span>
                </div>
                <div className="flex justify-between items-center p-3 bg-gray-700/40 rounded-xl">
                  <span className="text-gray-400">Risiko Medium</span>
                  <span className="text-lg font-bold text-yellow-400">{report.userStats.riskDistribution.MEDIUM}</span>
                </div>
                <div className="flex justify-between items-center p-3 bg-gray-700/40 rounded-xl">
                  <span className="text-gray-400">Risiko High</span>
                  <span className="text-lg font-bold text-red-400">{report.userStats.riskDistribution.HIGH}</span>
                </div>
              </div>
            </div>

            {/* Loan Stats */}
            <div className="bg-white/10 backdrop-blur-sm border border-white/20 rounded-2xl p-6 shadow-xl">
              <h3 className="text-xl font-bold text-white mb-6 flex items-center gap-2">
                <DollarSign className="w-5 h-5 text-purple-400" />
                Statistik Pinjaman
              </h3>
              <div className="grid grid-cols-2 gap-4 mb-6">
                <div className="text-center">
                  <div className="text-3xl font-bold text-purple-400">{report.loanStats.totalLoans}</div>
                  <div className="text-sm text-gray-400">Total Pinjaman</div>
                </div>
                <div className="text-center">
                  <div className="text-3xl font-bold text-cyan-400">{formatRupiah(report.loanStats.totalLoanAmount)}</div>
                  <div className="text-sm text-gray-400">Total Nominal</div>
                </div>
              </div>
              <div className="space-y-3">
                {Object.entries(report.loanStats.statusDistribution).map(([status, count]) => (
                  <div key={status} className="flex justify-between items-center p-3 bg-gray-700/40 rounded-xl">
                    <span className="text-gray-400">{status}</span>
                    <span className="text-lg font-bold text-white">{count}</span>
                  </div>
                ))}
              </div>
            </div>

            {/* Payment Stats */}
            <div className="bg-white/10 backdrop-blur-sm border border-white/20 rounded-2xl p-6 shadow-xl">
              <h3 className="text-xl font-bold text-white mb-6 flex items-center gap-2">
                <TrendingUp className="w-5 h-5 text-green-400" />
                Statistik Pembayaran
              </h3>
              <div className="grid grid-cols-3 gap-4 mb-6">
                <div className="text-center">
                  <div className="text-2xl font-bold text-cyan-400">{formatRupiah(report.paymentStats.totalDebt)}</div>
                  <div className="text-sm text-gray-400">Total Hutang</div>
                </div>
                <div className="text-center">
                  <div className="text-2xl font-bold text-green-400">{formatRupiah(report.paymentStats.totalPaid)}</div>
                  <div className="text-sm text-gray-400">Terbayar</div>
                </div>
                <div className="text-center">
                  <div className="text-2xl font-bold text-yellow-400">{formatRupiah(report.paymentStats.remainingDebt)}</div>
                  <div className="text-sm text-gray-400">Sisa</div>
                </div>
              </div>
              <div className="space-y-3">
                {Object.entries(report.paymentStats.statusDistribution).map(([status, count]) => (
                  <div key={status} className="flex justify-between items-center p-3 bg-gray-700/40 rounded-xl">
                    <span className="text-gray-400">{status}</span>
                    <span className="text-lg font-bold text-white">{count}</span>
                  </div>
                ))}
              </div>
            </div>

            {/* Audit Trail */}
            <div className="bg-white/10 backdrop-blur-sm border border-white/20 rounded-2xl p-6 shadow-xl">
              <h3 className="text-xl font-bold text-white mb-6 flex items-center gap-2">
                <Shield className="w-5 h-5 text-yellow-400" />
                Audit Trail
              </h3>
              <div className="mb-4 p-4 bg-gray-700/40 rounded-xl">
                <div className="text-sm text-gray-400">Total Log Audit</div>
                <div className="text-3xl font-bold text-yellow-400">{report.auditTrail.totalAuditLogs}</div>
              </div>
              <div className="space-y-3">
                {report.auditTrail.recentActivity.slice(0, 20).map((activity) => (
                  <div key={activity.id} className="p-4 bg-gray-700/30 rounded-xl">
                    <div className="flex items-start justify-between mb-2">
                      <div className="font-medium text-white">{activity.action}</div>
                      <div className="text-xs text-gray-500 flex items-center gap-1">
                        <Calendar className="w-3 h-3" />
                        {new Date(activity.createdAt).toLocaleString('id-ID')}
                      </div>
                    </div>
                    <div className="text-sm text-gray-400">{activity.description}</div>
                  </div>
                ))}
              </div>
            </div>
          </div>
        )}
      </div>
    </DashboardLayout>
  );
}
